#include "Test.h"
int main(void) {
  GRAPHICS_TYPE(TSurface) s = {0};
  GUI_TYPE(TContext) c = {0};
  GUI_TYPE(TList) list = {0};
  GUI_TYPE(TDialog) dialog = {0};
  const char *items[] = {"One", "Two", "Three", "Four", "Five"};
  size_t selected = 0;
  TQUAD_TYPE(float) r;
  bool fired = true;
  OK(GRAPHICS_FUNC(Surface_Create)(&s, (TDUAL_TYPE(uint32)){.x = 240, .y = 160}));
  list.id = 9;
  list.region = rect(0, 0, 100, 32);
  list.items = items;
  list.count = 5;
  list.selected = &selected;
  OK(GUI_FUNC(Begin)(&c, &s));
  OK(GUI_FUNC(ListEx)(&c, &list));
  OK(GUI_FUNC(End)(&c));
  OK(GUI_FUNC(Begin)(&c, &s));
  key(&c, LIB_PREFIX_CONST(INPUT_KEY_END), 0);
  key(&c, LIB_PREFIX_CONST(INPUT_KEY_ENTER), 0);
  OK(GUI_FUNC(MenuEx)(&c, &list));
  assert(selected == 4 && list.firstVisible == 3 && list.activated);
  OK(GUI_FUNC(End)(&c));
  OK(GUI_FUNC(Begin)(&c, &s));
  OK(GUI_FUNC(Row_Begin)(&c, rect(0, 0, 100, 30), 5));
  OK(GUI_FUNC(Layout_Next)(&c, 40, &r));
  assert(r.value1 == 0 && r.value3 == 40);
  OK(GUI_FUNC(Layout_Next)(&c, 40, &r));
  assert(r.value1 == 45);
  assert(GUI_FUNC(Layout_Next)(&c, 20, &r) == STATUS_CONST(OUT_OF_RANGE));
  OK(GUI_FUNC(Layout_End)(&c));
  OK(GUI_FUNC(Panel_Begin)(&c, rect(0, 40, 150, 100), "Panel"));
  OK(GUI_FUNC(Label)(&c, rect(10, 70, 80, 20), "Inside"));
  OK(GUI_FUNC(Panel_End)(&c));
  OK(GUI_FUNC(End)(&c));
  OK(GUI_FUNC(Begin)(&c, &s));
  position(&c, 30, 10);
  {
    INPUT_TYPE(TEvent) e = {0};
    e.type = INPUT_CONST(EVENT_MOUSE_SCROLL);
    e.data.motion.y = 2;
    OK(GUI_FUNC(Event)(&c, &e));
  }
  OK(GUI_FUNC(ListEx)(&c, &list));
  assert(list.firstVisible == 1);
  OK(GUI_FUNC(End)(&c));
  OK(GUI_FUNC(Begin)(&c, &s));
  OK(GUI_FUNC(ListEx)(&c, &list));
  assert(list.firstVisible == 1);
  OK(GUI_FUNC(End)(&c));
  dialog.id = 100;
  dialog.title = "Modal";
  dialog.message = "Proceed?";
  dialog.region = rect(20, 20, 180, 110);
  OK(GUI_FUNC(Begin)(&c, &s));
  dialog.title = "\xC0\xAF";
  assert(GUI_FUNC(ConfirmEx)(&c, &dialog) == STATUS_CONST(INVALID_SEQUENCE));
  assert(c.commandCount == 0 && c.modal == 0);
  dialog.title = "Modal";
  OK(GUI_FUNC(ConfirmEx)(&c, &dialog));
  OK(GUI_FUNC(Button)(&c, rect(0, 0, 70, 20), "Background", &fired));
  assert(!fired);
  OK(GUI_FUNC(End)(&c));
  assert(c.commands[c.commandCount - 1].overlay);
  OK(GUI_FUNC(Begin)(&c, &s));
  key(&c, LIB_PREFIX_CONST(INPUT_KEY_ESCAPE), 0);
  OK(GUI_FUNC(ConfirmEx)(&c, &dialog));
  assert(dialog.rejected);
  OK(GUI_FUNC(End)(&c));
  OK(GUI_FUNC(Begin)(&c, &s));
  OK(GUI_FUNC(ProgressBar)(&c, rect(0, 0, 80, 20), 3, 5));
  OK(GUI_FUNC(Progress)(&c, rect(0, 30, 80, 20), 0.5f));
  OK(GUI_FUNC(StatusBar)(&c, rect(0, 60, 200, 20), "Ready", "C11"));
  OK(GUI_FUNC(Toast)(&c, rect(0, 90, 100, 20), "Saved", true));
  OK(GUI_FUNC(Spinner)(&c, rect(0, 120, 100, 20), "Busy", 2));
  OK(GUI_FUNC(End)(&c));
  GRAPHICS_FUNC(Surface_Free)(&s);
  puts("Containers passed");
  return 0;
}
