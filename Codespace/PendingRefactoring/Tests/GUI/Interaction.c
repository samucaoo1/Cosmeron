#include "Test.h"
int main(void) {
  GRAPHICS_TYPE(TSurface) s = {0};
  GUI_TYPE(TContext) c = {0};
  bool fired = true, checked = false;
  float value = 0;
  GUI_TYPE(TButton) b = {0};
  b.region = rect(10, 10, 80, 25);
  b.label = "Save";
  b.id = 42;
  OK(GRAPHICS_FUNC(Surface_Create)(&s, (TDUAL_TYPE(uint32)){.x = 200, .y = 120}));
  OK(GUI_FUNC(Begin)(&c, &s));
  position(&c, 20, 20);
  mouse(&c, true);
  OK(GUI_FUNC(ButtonEx)(&c, &b));
  assert(!b.pressed);
  OK(GUI_FUNC(End)(&c));
  OK(GUI_FUNC(Begin)(&c, &s));
  position(&c, 150, 100);
  mouse(&c, false);
  OK(GUI_FUNC(ButtonEx)(&c, &b));
  assert(!b.pressed);
  OK(GUI_FUNC(End)(&c));
  OK(GUI_FUNC(Begin)(&c, &s));
  position(&c, 20, 20);
  mouse(&c, true);
  mouse(&c, false);
  position(&c, 150, 100);
  OK(GUI_FUNC(ButtonEx)(&c, &b));
  assert(b.pressed);
  OK(GUI_FUNC(End)(&c));
  OK(GUI_FUNC(Begin)(&c, &s));
  key(&c, LIB_PREFIX_CONST(INPUT_KEY_ENTER), 0);
  OK(GUI_FUNC(ButtonEx)(&c, &b));
  assert(b.pressed);
  OK(GUI_FUNC(Checkbox)(&c, rect(10, 50, 80, 25), "Check", &checked));
  assert(!checked);
  OK(GUI_FUNC(End)(&c));
  OK(GUI_FUNC(Begin)(&c, &s));
  key(&c, LIB_PREFIX_CONST(INPUT_KEY_TAB), 0);
  key(&c, LIB_PREFIX_CONST(INPUT_KEY_SPACE), 0);
  OK(GUI_FUNC(ButtonEx)(&c, &b));
  OK(GUI_FUNC(Checkbox)(&c, rect(10, 50, 80, 25), "Check", &checked));
  assert(checked);
  OK(GUI_FUNC(End)(&c));
  OK(GUI_FUNC(Begin)(&c, &s));
  position(&c, 30, 90);
  mouse(&c, true);
  OK(GUI_FUNC(Slider)(&c, rect(10, 80, 100, 20), 0, 100, &value));
  assert(value == 20);
  OK(GUI_FUNC(End)(&c));
  OK(GUI_FUNC(Begin)(&c, &s));
  position(&c, 190, 90);
  OK(GUI_FUNC(Slider)(&c, rect(10, 80, 100, 20), 0, 100, &value));
  assert(value == 100);
  OK(GUI_FUNC(End)(&c));
  OK(GUI_FUNC(Begin)(&c, &s));
  {
    INPUT_TYPE(TEvent) e = {0};
    e.type = INPUT_CONST(EVENT_FOCUS_LOST);
    OK(GUI_FUNC(Event)(&c, &e));
  }
  OK(GUI_FUNC(Slider)(&c, rect(10, 80, 100, 20), 0, 100, &value));
  assert(!c.held && !c.down);
  OK(GUI_FUNC(End)(&c));
  OK(GUI_FUNC(Begin)(&c, &s));
  OK(GUI_FUNC(Button)(&c, rect(0, 0, 80, 20), "same", &fired));
  assert(!fired);
  fired = true;
  assert(GUI_FUNC(Button)(&c, rect(0, 30, 80, 20), "same", &fired) == STATUS_CONST(ALREADY_EXISTS));
  assert(fired);
  OK(GUI_FUNC(PushId)(&c, "second"));
  OK(GUI_FUNC(Button)(&c, rect(0, 30, 80, 20), "same", &fired));
  OK(GUI_FUNC(PopId)(&c));
  OK(GUI_FUNC(End)(&c));
  GRAPHICS_FUNC(Surface_Free)(&s);
  puts("Interaction passed");
  return 0;
}
