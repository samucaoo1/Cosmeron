#!/usr/bin/env python3
"""Embed a .asf or .flf font as immutable bytes in a C11 header.

Usage:
  python3 Tools/asf_compile.py Fonts/Retro.asf -o Fonts/Retro.asf.h --symbol Retro_Font
  #include "Retro.asf.h"
  FONT_FUNC(ParseASF)((const char *)Retro_Font_Data,
                      sizeof(Retro_Font_Data), &font);

The resulting header has internal linkage and needs no external object files.
It includes no untrusted source text as C expressions.
"""
from __future__ import annotations
import argparse
from pathlib import Path
import re
import sys

def convert(source: Path, output: Path, symbol: str) -> None:
    if source.suffix.lower() not in {".asf", ".flf"}:
        raise ValueError("expected a .asf or .flf source")
    if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", symbol):
        raise ValueError("--symbol must be a valid C identifier")
    data = source.read_bytes()
    if not data:
        raise ValueError("empty font source")
    if source.suffix.lower() == ".asf" and not data.startswith(b"ASF1 "):
        raise ValueError("invalid ASF1 signature")
    if source.suffix.lower() == ".flf" and not data.startswith(b"flf2a"):
        raise ValueError("invalid FIGlet flf2a signature")
    items = [f"0x{b:02X}" for b in data]
    rows = [", ".join(items[i:i+12]) for i in range(0, len(items), 12)]
    payload = ",\n    ".join(rows)
    header = (
        "#pragma once\n"
        "/* Generated by Tools/asf_compile.py. Do not edit manually. */\n"
        f"static const unsigned char {symbol}_Data[] = {{\n"
        f"    {payload}\n"
        "};\n"
    )
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(header, encoding="ascii", newline="\n")

def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path)
    parser.add_argument("-o", "--output", type=Path, required=True)
    parser.add_argument("--symbol", default="FontAsset")
    args = parser.parse_args()
    try:
        convert(args.source, args.output, args.symbol)
    except (OSError, ValueError) as exc:
        print(f"asf_compile: {exc}", file=sys.stderr)
        return 1
    return 0

if __name__ == "__main__":
    raise SystemExit(main())
