"""Vendor miniz 3.1.0 (174573d60290f447c13a2b1b3405de2b96e27d6c).
Usage: python3 Tools/vendor_miniz.py /path/to/miniz-3.1.0
Preserve upstream copyright; isolate vendor identifiers and give exported
functions internal linkage so every TU can include the complete engine.
"""
import re
import sys
from pathlib import Path
src = Path(sys.argv[1])
out = Path(__file__).resolve().parents[1] / 'Codespace/Cosmeron/Modules/Compression/Vendor'
headers = ['miniz.h', 'miniz_common.h', 'miniz_tdef.h', 'miniz_tinfl.h', 'miniz_zip.h']
sources = ['miniz.c', 'miniz_tdef.c', 'miniz_tinfl.c', 'miniz_zip.c']
text = '\n'.join((src / f).read_text() for f in headers + sources)
text = re.sub(r'^#include "miniz[^\"]*\.h"\s*$', '', text, flags=re.M)
text = text.replace('extern MINIZ_EXPORT', 'MINIZ_EXPORT')
# Upstream declares these filesystem helpers even with NO_STDIO.
text = re.sub(r'^.*MINIZ_EXPORT.*mz_zip_add_mem_to_archive_file_in_place(?:_v2)?\(.*;\s*$', '', text, flags=re.M)
# Deterministic valid DOS date: 1980-01-01 (time disabled).
text = text.replace('dos_time = 0, dos_date = 0;', 'dos_time = 0, dos_date = 0x21;')
# Fix upstream temporary-compressor leaks on early heap-write failures.
start = text.index('        if (!mz_zip_writer_write_zeros(pZip, cur_archive_file_ofs')
end = text.index('        pComp = NULL;', start)
part = text[start:end]
# The final free remains; remove existing early frees and put one on every return.
last = part.rfind('        pZip->m_pFree(pZip->m_pAlloc_opaque, pComp);')
body, tail = part[:last], part[last:]
body = body.replace('pZip->m_pFree(pZip->m_pAlloc_opaque, pComp);', '')
body = re.sub(r'return ([^;]+);', r'{ pZip->m_pFree(pZip->m_pAlloc_opaque, pComp); return \1; }', body)
text = text[:start] + body + tail + text[end:]
text = re.sub(r'\b(?:mz_|tinfl_|tdefl_|miniz_|s_|MZ_|MINIZ_|TINFL_|TDEFL_)[A-Za-z0-9_]*\b', lambda m: 'cosmeron_compression_vendor_' + m[0], text)
pre = '''/* Generated by Tools/vendor_miniz.py. Upstream miniz 3.1.0. */
#pragma once
#define cosmeron_compression_vendor_MINIZ_EXPORT static inline
#define cosmeron_compression_vendor_MINIZ_NO_STDIO
#define cosmeron_compression_vendor_MINIZ_NO_TIME
#define cosmeron_compression_vendor_MINIZ_NO_ZLIB_COMPATIBLE_NAMES
#define cosmeron_compression_vendor_MINIZ_USE_UNALIGNED_LOADS_AND_STORES 0
#if defined(__clang__)
#pragma clang diagnostic push
#pragma clang diagnostic ignored "-Wunused-function"
#pragma clang diagnostic ignored "-Wtautological-constant-out-of-range-compare"
#elif defined(__GNUC__)
#pragma GCC diagnostic push
#pragma GCC diagnostic ignored "-Wunused-function"
#elif defined(_MSC_VER)
#pragma warning(push, 0)
#endif
'''
post = '''
#if defined(__clang__)
#pragma clang diagnostic pop
#elif defined(__GNUC__)
#pragma GCC diagnostic pop
#elif defined(_MSC_VER)
#pragma warning(pop)
#endif
'''
text = re.sub(r'[ \t]+$', '', text, flags=re.M)
(out / 'Miniz.inc').write_text(pre + text + post)
(out / 'LICENSE.txt').write_text((src / 'LICENSE').read_text())
